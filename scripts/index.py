#!/usr/bin/env python3
"""Rebuild the index.md of every log folder from the front matter of its files.

Nobody edits an index.md, and pull requests never include one, so two PRs can't conflict over them.
The "indexes" GitHub Action runs this on main after every merge and commits the result.

    python3 scripts/index.py          # rewrite the indexes (the bot does this; locally only to preview)
    python3 scripts/index.py --check  # CI on PRs: fail if any file has bad or missing front matter
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP = {"index.md", "TEMPLATE.md", "README.md"}

# folder: (heading, one-line purpose, columns, required fields, how to sort, group by first tag?)
FOLDERS = {
    "plans": ("Plans", "One plan per GitHub issue. The issue tracks status; the plan says how.",
              ["issue", "title", "workstream", "owner", "status"], ["issue", "title", "workstream", "status"], "issue", False),
    "changes": ("Change log", "One file per change: what changed, who did it, and how AI was used.",
                ["date", "title", "owner", "issue", "ai_used"], ["date", "title", "owner", "ai_used"], "date", False),
    "decisions": ("Decisions", "One file per decision (ADR). To reverse one, write a new file that supersedes it.",
                  ["date", "title", "status", "issue"], ["date", "title", "status"], "date", False),
    "knowledge": ("Knowledge", "One idea per file, from lectures, readings, labs and Prosits.",
                  ["title", "source"], ["title", "tags", "source"], "title", True),
    "learnings": ("Learnings", "One thing we learned by doing, per file.",
                  ["date", "title", "owner"], ["date", "title", "owner", "tags"], "date", True),
}


def front_matter(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{path.relative_to(ROOT)}: no front matter (start the file with ---)")
    meta = {}
    for line in lines[1:]:
        if line.strip() == "---":
            return meta
        key, sep, value = line.partition(":")
        if sep:
            meta[key.strip()] = value.strip().strip("\"'")
    raise ValueError(f"{path.relative_to(ROOT)}: front matter is not closed with ---")


def tags(meta):
    return [t.strip() for t in meta.get("tags", "").strip("[]").split(",") if t.strip()]


def cell(value):
    return str(value).replace("|", "\\|")


def table(rows, columns):
    out = ["| " + " | ".join(c.replace("_", " ").capitalize() for c in columns) + " |",
           "|" + "---|" * len(columns)]
    for name, meta in rows:
        cells = [f"[{cell(meta['title'])}]({name})" if c == "title" else cell(meta.get(c, "")) for c in columns]
        out.append("| " + " | ".join(cells) + " |")
    return out


def build(folder):
    heading, purpose, columns, required, sort_key, grouped = FOLDERS[folder]
    errors, rows = [], []
    for path in sorted((ROOT / folder).glob("*.md")):
        if path.name in SKIP:
            continue
        try:
            meta = front_matter(path)
        except ValueError as e:
            errors.append(str(e))
            continue
        missing = [f for f in required if not meta.get(f)]
        if missing:
            errors.append(f"{folder}/{path.name}: missing {', '.join(missing)}")
            continue
        rows.append((path.name, meta))

    if sort_key == "issue":
        rows.sort(key=lambda r: int(r[1]["issue"].lstrip("#") or 0))
    elif sort_key == "date":
        rows.sort(key=lambda r: (r[1]["date"], r[1]["title"]), reverse=True)
    else:
        rows.sort(key=lambda r: r[1]["title"].lower())

    out = [f"# {heading}", "", f"{purpose} {len(rows)} files.", "",
           "_Generated by `python3 scripts/index.py`. Do not edit by hand. Template: [TEMPLATE.md](TEMPLATE.md)._", ""]
    if grouped:
        groups = {}
        for row in rows:
            groups.setdefault((tags(row[1]) or ["untagged"])[0], []).append(row)
        for tag in sorted(groups):
            out += [f"## {tag}", ""] + table(groups[tag], columns) + [""]
    else:
        out += table(rows, columns) + [""]
    return "\n".join(out), errors


def main(check):
    changed, errors = [], []
    for folder in FOLDERS:
        text, errs = build(folder)
        errors += errs
        index = ROOT / folder / "index.md"
        if not check and (not index.exists() or index.read_text(encoding="utf-8") != text):
            index.write_text(text, encoding="utf-8")
            changed.append(f"{folder}/index.md")
    for e in errors:
        print("ERROR", e)
    if not check:
        print("Updated:", ", ".join(changed) or "nothing (all up to date)")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
